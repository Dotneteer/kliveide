/**
 * Writes docs/zxbasic.tmLanguage.json: the TextMate grammar the docs site uses to highlight ZX BASIC
 * code blocks (```zxbasic), registered in docs/next.config.mjs.
 *
 * The keyword lists are the IDE editor's own: `monarchWordLists()` from src/common/kbasic/help.ts,
 * which reads the generated help data (from .ai/zxbasic-syntax/ and Klive's stdlib). So the site
 * and the editor agree on what is a statement, an operator, a function, a type or a directive;
 * test/docs/zxbasic-grammar.test.ts fails when the committed grammar falls behind them. Regenerate
 * with `npm run doc:grammar` after `npm run kbasic:help`.
 *
 * Usage: node scripts/build-doc-zxbasic-grammar.cjs [--check]
 */
const { readFileSync, writeFileSync, existsSync } = require("node:fs");
const { join } = require("node:path");

const repoRoot = join(__dirname, "..");
const target = join(repoRoot, "docs", "zxbasic.tmLanguage.json");

function wordLists() {
  const jiti = require("jiti")(__filename, { interopDefault: true });
  const { monarchWordLists } = jiti(join(repoRoot, "src", "common", "kbasic", "help.ts"));
  return monarchWordLists();
}

/** A case-insensitive alternation of whole words; names may end in `$` (CHR$, INKEY$). */
function words(list) {
  const unique = [...new Set(list.map((w) => w.toUpperCase()))].sort((a, b) => b.length - a.length || a.localeCompare(b));
  const alternation = unique.map((w) => w.replace(/[$.*+?^{}()|[\]\\]/g, "\\$&")).join("|");
  return `(?i)(?<![\\w$])(?:${alternation})(?![\\w$])`;
}

function buildGrammar() {
  const w = wordLists();
  const directives = [...new Set(w.directives.map((d) => d.replace(/^#/, "").toLowerCase()))]
    .sort((a, b) => b.length - a.length)
    .join("|");
  return {
    $comment:
      "Generated by scripts/build-doc-zxbasic-grammar.cjs from the IDE's ZX BASIC word lists. Do not edit.",
    name: "ZX BASIC",
    scopeName: "source.zxbasic",
    patterns: [
      { include: "#asm" },
      { include: "#comment" },
      { include: "#string" },
      { include: "#directive" },
      { include: "#number" },
      { include: "#keyword" },
      { include: "#label" },
      { include: "#operator" }
    ],
    repository: {
      // --- ASM ... END ASM: the block's lines are Z80 assembly
      asm: {
        begin: "(?i)(?<![\\w$])(asm)(?![\\w$])",
        end: "(?i)(?<![\\w$])(end\\s+asm)(?![\\w$])",
        beginCaptures: { 1: { name: "keyword.control.zxbasic" } },
        endCaptures: { 1: { name: "keyword.control.zxbasic" } },
        patterns: [{ include: "source.z80klive" }]
      },
      comment: {
        patterns: [
          { name: "comment.block.zxbasic", begin: "/'", end: "'/" },
          { name: "comment.line.quote.zxbasic", match: "'.*$" },
          { name: "comment.line.rem.zxbasic", match: "(?i)(?<![\\w$])REM(?![\\w$]).*$" }
        ]
      },
      string: {
        name: "string.quoted.double.zxbasic",
        begin: '"',
        end: '"',
        patterns: [{ name: "constant.character.escape.zxbasic", match: "\\\\(?:#[0-9]{3}|[ipbf][0-9]|[A-U*`\\\\]|[ .':]{2})" }]
      },
      directive: {
        name: "keyword.control.directive.zxbasic",
        match: `(?i)#(?:${directives})\\b`
      },
      number: {
        patterns: [
          { name: "constant.numeric.hex.zxbasic", match: "(?i)(?:\\$[0-9a-f]+|\\b0x[0-9a-f]+\\b|\\b[0-9][0-9a-f]*h\\b)" },
          { name: "constant.numeric.binary.zxbasic", match: "(?i)(?:%[01]+\\b|\\b[01]+b\\b)" },
          { name: "constant.numeric.decimal.zxbasic", match: "(?i)(?:\\b[0-9]+\\.?[0-9]*|\\.[0-9]+)(?:e[+-]?[0-9]+)?\\b" }
        ]
      },
      keyword: {
        patterns: [
          { name: "storage.type.zxbasic", match: words(w.types) },
          { name: "keyword.operator.word.zxbasic", match: words(w.operators.filter((o) => /^[A-Za-z]/.test(o))) },
          { name: "support.function.zxbasic", match: words(w.functions) },
          { name: "keyword.control.zxbasic", match: words(w.statements) }
        ]
      },
      // --- A label at the start of a line (`Loop:`) or a line number
      label: {
        patterns: [
          { name: "entity.name.label.zxbasic", match: "^\\s*[A-Za-z_][A-Za-z0-9_]*:(?!=)" },
          { name: "constant.numeric.line.zxbasic", match: "^\\s*[0-9]+(?=\\s)" }
        ]
      },
      operator: {
        name: "keyword.operator.zxbasic",
        match: "<>|<=|>=|<<|>>|[-+*/^=<>&|~!@]"
      }
    }
  };
}

function render() {
  return JSON.stringify(buildGrammar(), null, 2) + "\n";
}

if (require.main === module) {
  const text = render();
  if (process.argv.includes("--check")) {
    const ok = existsSync(target) && readFileSync(target, "utf8") === text;
    console.log(ok ? "zxbasic grammar is up to date." : "docs/zxbasic.tmLanguage.json is out of date: run `npm run doc:grammar`.");
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(target, text);
  console.log(`Wrote ${target}`);
}

module.exports = { render };
