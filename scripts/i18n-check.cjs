/**
 * The localization gate (`.plans/LOCALIZATION_PLAN.md` §2).
 *
 * Reads the message catalogs in `src/common/i18n/locales/` and the TypeScript sources, and fails
 * (exit 1) on:
 *   - an English entry that is not valid ICU, has a malformed or duplicated key, lacks its
 *     `@key` context, or uses placeholders its `@key.placeholders` does not describe;
 *   - a translation with invalid ICU, different placeholders from English, `@` metadata (context
 *     lives only in English, D4), or a key English no longer has (stale);
 *   - a key used in code (`t("...")`) that English does not define;
 *   - an English namespace file that `catalogs.ts` does not import;
 *   - `keys.generated.ts` or `translations.generated.ts` out of date.
 * It warns on: English keys no source file mentions, `maxChars` exceeded (the overflow worklist),
 * translations whose English changed since they were made (outdated: `<lang>/.source.json` holds
 * the English each translation was made from), and Portuguese text that uses the other variant's
 * words (`glossary.json` `variantOnly`).
 *
 * `maxChars` counts the literal text only: placeholders count zero, `#` counts one, and a
 * plural/select counts its longest branch.
 *
 * Usage:
 *   npm run i18n:check             check; exit 1 on errors
 *   npm run i18n:keys              regenerate keys.generated.ts and translations.generated.ts, then check
 */
const fs = require("fs");
const path = require("path");
const lib = require("./i18n-lib.cjs");

const { REPO, SOURCE_LANGUAGE, PSEUDO_LANGUAGE, KEY_PATTERN, rel } = lib;
const DEFAULTS = {
  localesDir: lib.LOCALES_DIR,
  sourceDirs: [path.join(REPO, "src")],
  catalogsFile: path.join(REPO, "src/common/i18n/catalogs.ts"),
  keysFile: path.join(REPO, "src/common/i18n/keys.generated.ts"),
  translationsFile: path.join(REPO, "src/common/i18n/translations.generated.ts")
};
const T_CALL = /\bt\(\s*(["'`])([^"'`\n]+)\1/g;

function sameList(a, b) {
  return a.length === b.length && a.every((v, i) => v === b[i]);
}

function listSourceFiles(dirs, skip) {
  const out = [];
  const visit = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
        visit(full);
      } else if (/\.(ts|tsx)$/.test(entry.name) && !entry.name.endsWith(".d.ts") && !skip.has(full)) {
        out.push(full);
      }
    }
  };
  for (const dir of dirs) if (fs.existsSync(dir)) visit(dir);
  return out.sort();
}

/** The `keys.generated.ts` text for a list of English keys. */
function renderKeysFile(keys) {
  const header =
    "// Generated by `npm run i18n:keys` from src/common/i18n/locales/en/*.json - do not edit.\n" +
    "// Every key `t()` accepts; a misspelt key is a type error.\n";
  if (keys.length === 0) return `${header}export type MessageKey = never;\n`;
  return `${header}export type MessageKey =\n${keys.map((k) => `  | ${JSON.stringify(k)}`).join("\n")};\n`;
}

/** Words of one Portuguese variant found in a text of the other (the cheap variant-drift guard) */
function variantDrift(glossary, lang, text) {
  const other = lang === "pt-PT" ? "pt-BR" : lang === "pt-BR" ? "pt-PT" : undefined;
  const words = other ? (glossary.variantOnly[other] ?? []) : [];
  const lower = text.toLowerCase();
  return words.filter((w) => new RegExp(`(^|[^\\p{L}])${w.toLowerCase()}($|[^\\p{L}])`, "u").test(lower));
}

/**
 * Runs every check. Returns `{ errors, warnings, info, keys, status }`; with `update`, rewrites the
 * generated files first. `status` maps each language to `{ translated, total, outdated }`.
 */
async function checkI18n(options = {}) {
  const opts = { ...DEFAULTS, ...options };
  const parser = await lib.loadParser();
  const errors = [];
  const warnings = [];
  const info = [];
  const status = {};

  // --- English: the source, with context
  const { namespaces, raw } = lib.loadEnglish(opts.localesDir, errors);
  const english = new Map(); // key -> { text, meta, ns, placeholders, length }
  if (namespaces.length === 0) errors.push(`${rel(path.join(opts.localesDir, SOURCE_LANGUAGE))}: no English namespace files`);
  for (const ns of namespaces) {
    const data = raw[ns];
    const where = rel(path.join(opts.localesDir, SOURCE_LANGUAGE, `${ns}.json`));
    for (const [entryKey, value] of Object.entries(data)) {
      if (entryKey.startsWith("@")) {
        if (!(entryKey.slice(1) in data)) errors.push(`${where}: "${entryKey}" describes a key that does not exist`);
        if (!value || typeof value !== "object" || Array.isArray(value)) errors.push(`${where}: "${entryKey}" must be an object`);
        continue;
      }
      const key = entryKey;
      if (!KEY_PATTERN.test(key)) errors.push(`${where}: "${key}" is not a dotted, area-first key (e.g. "menu.file.openFile")`);
      if (english.has(key)) {
        errors.push(`${where}: "${key}" is also defined in ${english.get(key).ns}.json`);
        continue;
      }
      if (typeof value !== "string") {
        errors.push(`${where}: "${key}" must be a string`);
        continue;
      }
      const meta = data[`@${key}`];
      const metaObj = meta && typeof meta === "object" && !Array.isArray(meta) ? meta : {};
      if (typeof metaObj.context !== "string" || metaObj.context.trim() === "") {
        errors.push(`${where}: "${key}" needs translator context in "@${key}".context`);
      }
      if (metaObj.maxChars !== undefined && !(Number.isInteger(metaObj.maxChars) && metaObj.maxChars > 0)) {
        errors.push(`${where}: "@${key}".maxChars must be a positive integer`);
      }
      const parsed = lib.parseMessage(parser, value);
      if (parsed.error) {
        errors.push(`${where}: "${key}" is not valid ICU: ${parsed.error}`);
        english.set(key, { text: value, meta: metaObj, ns, placeholders: null, length: value.length });
        continue;
      }
      const { placeholders, length } = lib.analyze(parser, parsed.ast);
      const described = Object.keys(metaObj.placeholders ?? {}).sort();
      for (const name of placeholders) {
        if (!described.includes(name)) errors.push(`${where}: "${key}" uses {${name}}; describe it in "@${key}".placeholders`);
      }
      for (const name of described) {
        if (!placeholders.includes(name)) {
          errors.push(`${where}: "@${key}".placeholders describes {${name}}, which the message does not use`);
        }
      }
      if (metaObj.maxChars && length > metaObj.maxChars) {
        warnings.push(`en: "${key}" is ${length} chars, over its maxChars ${metaObj.maxChars}`);
      }
      english.set(key, { text: value, meta: metaObj, ns, placeholders, length });
    }
  }

  // --- Translations: text only, checked against English
  const glossary = lib.loadGlossary(opts.localesDir);
  for (const lang of lib.listLanguages(opts.localesDir)) {
    const langDir = path.join(opts.localesDir, lang);
    if (lang === PSEUDO_LANGUAGE) {
      errors.push(`${rel(langDir)}: "qps" is generated at run time from English; delete the folder`);
      continue;
    }
    const loaded = lib.loadLanguage(opts.localesDir, lang, errors);
    let translated = 0;
    let outdated = 0;
    for (const [ns, data] of Object.entries(loaded.files)) {
      const where = rel(path.join(langDir, `${ns}.json`));
      if (!namespaces.includes(ns)) {
        errors.push(`${where}: English has no "${ns}" namespace`);
        continue;
      }
      for (const [key, value] of Object.entries(data)) {
        if (key.startsWith("@")) {
          errors.push(`${where}: "${key}" - context lives only in English`);
          continue;
        }
        const source = english.get(key);
        if (!source) {
          errors.push(`${where}: "${key}" is stale - English no longer has it`);
          continue;
        }
        if (source.ns !== ns) errors.push(`${where}: "${key}" belongs in ${source.ns}.json`);
        if (typeof value !== "string") {
          errors.push(`${where}: "${key}" must be a string`);
          continue;
        }
        const parsed = lib.parseMessage(parser, value);
        if (parsed.error) {
          errors.push(`${where}: "${key}" is not valid ICU: ${parsed.error}`);
          continue;
        }
        const { placeholders, length } = lib.analyze(parser, parsed.ast);
        if (source.placeholders && !sameList(placeholders, source.placeholders)) {
          errors.push(
            `${where}: "${key}" uses {${placeholders.join("}, {")}} but English uses {${source.placeholders.join("}, {")}}`
          );
        }
        if (source.meta.maxChars && length > source.meta.maxChars) {
          warnings.push(`${lang}: "${key}" is ${length} chars, over its maxChars ${source.meta.maxChars}`);
        }
        for (const word of variantDrift(glossary, lang, value)) {
          warnings.push(`${lang}: "${key}" uses "${word}", a word of the other Portuguese variant`);
        }
        translated++;
        if (loaded.sources[key] !== source.text) {
          outdated++;
          warnings.push(`${lang}: "${key}" is outdated - English changed since it was translated`);
        }
      }
    }
    for (const key of Object.keys(loaded.sources)) {
      if (!english.has(key)) warnings.push(`${rel(loaded.sourcesFile)}: "${key}" no longer exists in English`);
    }
    const total = english.size;
    const pct = total === 0 ? 100 : Math.floor((translated * 100) / total);
    status[lang] = { translated, total, outdated };
    info.push(`${lang}: ${pct} % translated (${translated}/${total}), ${outdated} outdated`);
  }

  // --- catalogs.ts must bundle every English namespace
  if (fs.existsSync(opts.catalogsFile)) {
    const catalogsText = fs.readFileSync(opts.catalogsFile, "utf8");
    for (const ns of namespaces) {
      if (!catalogsText.includes(`./locales/${SOURCE_LANGUAGE}/${ns}.json`)) {
        errors.push(`${rel(opts.catalogsFile)}: does not import ${SOURCE_LANGUAGE}/${ns}.json`);
      }
    }
  }

  // --- Keys used in code
  const skip = new Set([path.resolve(opts.keysFile), path.resolve(opts.translationsFile)]);
  const sources = listSourceFiles(opts.sourceDirs, skip);
  const allText = [];
  for (const file of sources) {
    const text = fs.readFileSync(file, "utf8");
    allText.push(text);
    for (const match of text.matchAll(T_CALL)) {
      if (match[1] === "`" && match[2].includes("${")) continue;
      const key = match[2];
      if (!KEY_PATTERN.test(key) || english.has(key)) continue;
      const line = text.slice(0, match.index).split("\n").length;
      errors.push(`${rel(file)}:${line}: t("${key}") - English has no such key`);
    }
  }
  const joined = allText.join("\n");
  for (const key of english.keys()) {
    if (!joined.includes(`"${key}"`) && !joined.includes(`'${key}'`) && !joined.includes(`\`${key}\``)) {
      warnings.push(`en: "${key}" is not used by any source file`);
    }
  }

  // --- The generated files
  const keys = [...english.keys()].sort();
  const generated = [
    [opts.keysFile, renderKeysFile(keys)],
    [opts.translationsFile, lib.renderTranslationsFile(opts.localesDir)]
  ];
  for (const [file, expected] of generated) {
    if (opts.update) {
      fs.writeFileSync(file, expected);
    } else {
      const actual = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
      if (actual !== expected) errors.push(`${rel(file)}: out of date - run \`npm run i18n:keys\``);
    }
  }

  return { errors, warnings, info, keys, status };
}

async function main() {
  const update = process.argv.includes("--update");
  const { errors, warnings, info, keys } = await checkI18n({ update });
  for (const line of info) console.log(line);
  for (const line of warnings) console.warn(`warning: ${line}`);
  for (const line of errors) console.error(`error: ${line}`);
  console.log(
    `i18n: ${keys.length} English keys, ${errors.length} error(s), ${warnings.length} warning(s)` +
      (update ? " - generated files updated" : "")
  );
  process.exitCode = errors.length > 0 ? 1 : 0;
}

if (require.main === module) {
  main().catch((err) => {
    console.error(err);
    process.exitCode = 1;
  });
}

module.exports = { checkI18n, renderKeysFile };
