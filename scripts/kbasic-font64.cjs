function pack() {
  const rows = new Map(GLYPHS.map(([code, glyph]) => [code, [0, ...glyph.map((r) => [...r].reduce((v, c, i) => v | (c === "#" ? 4 >> i : 0), 0))]]));
  if (rows.size !== 96 || GLYPHS.some(([, g]) => g.length !== 7 || g.some((r) => !/^[#.]{3}$/.test(r)))) {
    throw new Error("kbasic-font64: every character 32-127 needs 7 rows of 3 pixels");
  }
  const bytes = [];
  for (let code = 32; code < 128; code += 2) {
    for (let k = 0; k < 8; k++) bytes.push((rows.get(code)[k] << 5) | (rows.get(code + 1)[k] << 1));
  }
  return bytes;
}

function table(bytes) {
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) lines.push("    " + bytes.slice(i, i + 16).join(", "));
  return `DIM __kbP64Font(0 TO 383) AS UByte => { _\n${lines.join(", _\n")} _\n}`;
}

function main() {
  const text = fs.readFileSync(FILE, "utf8").replace(/\r\n?/g, "\n");
  const re = /DIM __kbP64Font\(0 TO 383\) AS UByte => \{[^}]*\}/;
  if (!re.test(text)) throw new Error("kbasic-font64: print64.bas has no __kbP64Font table");
  const updated = text.replace(re, table(pack()));
  if (process.argv.includes("--check")) {
    if (updated !== text) {
      console.error("print64.bas's font table is out of date: run `node scripts/kbasic-font64.cjs`");
      process.exit(1);
    }
    console.log("print64.bas's font table is current.");
    return;
  }
  fs.writeFileSync(FILE, updated);
  console.log("Wrote the font table in src/main/kbasic/stdlib/print64.bas.");
}

if (require.main === module) main();

