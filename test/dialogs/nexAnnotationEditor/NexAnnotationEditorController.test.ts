describe("lifecycle", () => {
  it("unsubscribes from the session on dispose", async () => {
    const controller = await opened();
    controller.dispose();
    expect(fakes.session.unsubscribeCount).toEqual(1);
  });

  it("comes back alive and re-subscribed after a StrictMode teardown", async () => {
    // --- React runs every effect setup → cleanup → setup in development. A controller that could
    // --- only be disposed would return deaf to the session. Trap 1 in `.ai/ui-mvc-guide.md`.
    const controller = await opened();
    controller.dispose();
    controller.activate();

    expect(controller.isDisposed).toEqual(false);
    expect(fakes.session.subscribeCalls.length).toEqual(2);

    // --- And it still works.
    await controller.dispatch({ type: "rowSelected", index: 1, extend: false });
    expect(controller.state.selection).toEqual({ anchorIndex: 1, activeIndex: 1 });
  });

  it("ignores intents after disposal", async () => {
    const controller = await opened();
    controller.dispose();
    await controller.dispatch({ type: "rowSelected", index: 2, extend: false });
    expect(controller.state.selection).toEqual(undefined);
  });
});

