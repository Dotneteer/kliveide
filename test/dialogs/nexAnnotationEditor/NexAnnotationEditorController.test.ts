/*
 * Journey tests: every flow driven by dispatching intents against fakes, with no React and no DOM.
 *
 * `settle()` drains follow-up work transitively, so a handler that starts more work — a dialog whose
 * result triggers a publish, whose snapshot regenerates the listing — is fully awaited.
 */

let fakes: FakePorts;

function open(
  env: Partial<NexAnnotationEditorEnvironment> = {},
  options: Parameters<typeof createFakePorts>[0] & { items?: DisassemblyItem[] } = {}
) {
  const { items, ...portOptions } = options;
  fakes = createFakePorts(portOptions);
  const controller = new NexAnnotationEditorController(fakes.ports, anEnvironment(env));
  return { controller, items: items ?? aListing(6) };
}

/**
 * An opened editor with a listing already reported.
 *
 * The listing is generated by the component around the editor — a dump with no sidecar still
 * disassembles — so it arrives as an intent rather than being fetched.
 */
async function opened(
  env: Partial<NexAnnotationEditorEnvironment> = {},
  options: Parameters<typeof createFakePorts>[0] & { items?: DisassemblyItem[] } = {}
) {
  const { controller, items } = open(env, options);
  await controller.dispatch({ type: "opened" });
  await controller.dispatch({ type: "listingChanged", items });
  await controller.settle();
  return controller;
}

beforeEach(() => {
  fakes = createFakePorts();
});

describe("opening", () => {
  it("subscribes to the session for its own sidecar and bank", async () => {
    const controller = await opened();
    expect(fakes.session.subscribeCalls).toEqual([{ path: SIDECAR, bank: BANK }]);
    expect(controller.state.annotations).toBeDefined();
  });

  it("takes the listing the surrounding component reports", async () => {
    const controller = await opened();
    expect(controller.state.items.length).toEqual(6);
  });

  it("hands the loaded model out for the listing to be generated from", async () => {
    // --- The editor does not generate the listing; it publishes the model the component needs.
    const controller = await opened();
    expect(controller.viewModel.annotations).toBe(controller.state.annotations);
  });

  it("does not subscribe for a document with no sidecar", async () => {
    await opened({ annotationPath: undefined });
    expect(fakes.session.subscribeCalls).toEqual([]);
  });

  it("reports a sidecar that failed to load, and offers no model to annotate by", async () => {
    const session = new FakeSession({ annotations: undefined, loadError: "bad json" });
    const controller = await opened({}, { session });
    expect(controller.state.loadError).toEqual("bad json");
    expect(controller.viewModel.annotations).toEqual(undefined);
  });

  it("still holds the rows of an unannotated dump", async () => {
    // --- A popped-out loading screen has no sidecar but still disassembles, and the editor needs
    // --- those rows: selection works, even though every editing action is disabled.
    const session = new FakeSession({ annotations: undefined });
    const controller = await opened({ annotationPath: undefined }, { session });
    expect(controller.state.items.length).toEqual(6);
    await controller.dispatch({ type: "rowSelected", index: 2, extend: false });
    expect(controller.state.selection).toEqual({ anchorIndex: 2, activeIndex: 2 });
    expect(controller.viewModel.menu.every((entry) => entry.kind === "separator" || entry.disabled))
      .toEqual(true);
  });
});

describe("the environment changing", () => {
  it("re-subscribes when the bank changes", async () => {
    const controller = await opened();
    await controller.dispatch({ type: "environmentChanged", env: anEnvironment({ bank: 6 }) });
    await controller.settle();
    expect(fakes.session.subscribeCalls).toEqual([
      { path: SIDECAR, bank: BANK },
      { path: SIDECAR, bank: 6 }
    ]);
    expect(fakes.session.unsubscribeCount).toEqual(1);
  });

  it("does nothing at all for an unchanged environment", async () => {
    const controller = await opened();
    const before = controller.state;
    await controller.dispatch({ type: "environmentChanged", env: anEnvironment() });
    await controller.settle();
    // --- The same state object: the container derives the environment fresh on every render.
    expect(controller.state).toBe(before);
  });

  it("persists a changed display setting into the sidecar", async () => {
    const controller = await opened();
    await controller.dispatch({
      type: "environmentChanged",
      env: anEnvironment({ decimalView: true })
    });
    await controller.settle();
    expect(publishedBank(fakes.session, SIDECAR, BANK)?.decimalView).toEqual(true);
  });

  it("does not dirty the sidecar for settings that came out of it", async () => {
    // --- The document opens on the settings the sidecar remembers, so the first environment push
    // --- must not look like an edit.
    const session = new FakeSession({
      annotations: {
        schemaVersion: 1,
        banks: { [String(BANK)]: { offsetIndex: 1, decimalView: true, regions: [] } }
      },
      dirty: false,
      loading: false
    });
    const controller = await opened({ decimalView: true }, { session });
    await controller.dispatch({
      type: "environmentChanged",
      env: anEnvironment({ decimalView: true, viewMode: "memory" })
    });
    await controller.settle();
    // --- `viewMode` did change, so that one *is* an edit; `decimalView` alone would not have been.
    expect(publishedBank(fakes.session, SIDECAR, BANK)?.decimalView).toEqual(true);
  });
});

